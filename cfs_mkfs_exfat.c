/* cfs_mkfs_exfat — Self-contained exFAT formatter.
 * Writes both boot regions, the FAT, the allocation bitmap, the up-case
 * table and the root directory straight through the block device. */

#include "cfs.h"
#include <string.h>
#include <stdlib.h>
#include <stdio.h>
#include <time.h>
#include <unistd.h>

#define EXFAT_SECTOR    512
/* The two boot regions together are 24 sectors: each is 12 — boot sector,
 * 8 extended boot sectors, OEM parameters, reserved, then the region
 * checksum.  exFAT has no BackupBootSector field the way FAT32 has
 * BkBootSec; the backup region sits at the fixed sector 12, so the only
 * thing the boot sector owes it is a FatOffset that clears both regions. */
#define EXFAT_BOOT_SECT 24
#define EXFAT_FAT_OFF   24
#define EXFAT_FAT_ENTRY 4
#define EXFAT_EOF       0xFFFFFFFFu
#define EXFAT_FAT0      0xFFFFFFF8u   /* media descriptor, as in FAT */
#define EXFAT_FIRST_CLU 2             /* cluster 0 and 1 are reserved */
/* exFAT's legal cluster-count window: below the floor the volume is FAT
 * territory, above the ceiling ClusterCount (a 32-bit field) cannot say how
 * many clusters there are. */
#define EXFAT_MIN_CLUSTERS 0xFFF5u
#define EXFAT_MAX_CLUSTERS 0xFFFFFFF5u
/* SectorsPerClusterShift is 0..(25 - BytesPerSectorShift) and a cluster may
 * not exceed 32MB — 65536 sectors at 512 bytes/sector. */
#define EXFAT_MAX_SPC   (32u * 1024 * 1024 / EXFAT_SECTOR)
/* The standard up-case table: 5836 bytes of compressed BMP mapping, the one
 * every driver ships.  Its checksum over these exact bytes is 0xE619D30D,
 * which is the value the up-case entry has to carry. */
#define EXFAT_UPCASE_BYTES 5836
/* Defined at the foot of the file — it is 5836 bytes of table and nothing
 * reads better for being above the code that checksums it. */
static const uint8_t exfat_upcase[EXFAT_UPCASE_BYTES];

static void le16(uint8_t *p, uint16_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); }
static void le32(uint8_t *p, uint32_t v) {
    p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24);
}
static void le64(uint8_t *p, uint64_t v) { le32(p, (uint32_t)v); le32(p + 4, (uint32_t)(v >> 32)); }

/* The exFAT checksum: rotate the accumulator right one bit, add the next
 * byte.  On the boot sector VolumeFlags (106, 107) and PercentInUse (112)
 * are skipped so that a driver flipping them need not rewrite the checksum;
 * the up-case table uses the same recurrence over its whole length. */
static uint32_t exfat_checksum(const uint8_t *p, size_t n, int skip_boot) {
    uint32_t cs = 0;
    for (size_t i = 0; i < n; i++) {
        if (skip_boot && (i == 106 || i == 107 || i == 112)) continue;
        cs = ((cs & 1u) ? 0x80000000u : 0u) + (cs >> 1) + p[i];
    }
    return cs;
}

/* FATLength and ClusterCount are mutually dependent: the FAT has to hold
 * ClusterCount + 2 entries, but where the cluster heap starts — and so how
 * many clusters there are — depends on how long the FAT is.  Exactly one
 * pair satisfies both, and the closed form below lands within a sector or
 * two of it, so probe the neighbourhood instead of iterating.  A FAT one
 * sector short cannot hold the cluster table; one that is too long carries
 * entries for clusters that do not exist. */
static int exfat_layout(uint64_t vol_sects, uint32_t spc,
                        uint32_t *fat_len, uint32_t *clu_count) {
    const uint64_t per_sector = EXFAT_SECTOR / EXFAT_FAT_ENTRY;   /* 128 */
    if (spc == 0 || vol_sects <= EXFAT_FAT_OFF + 1) return -1;
    uint64_t room = vol_sects - EXFAT_FAT_OFF;
    uint64_t est = room / (per_sector * spc + 1);
    for (int64_t d = -4; d <= 16; d++) {
        int64_t l = (int64_t)est + d;
        if (l <= 0 || (uint64_t)l >= room) continue;
        uint64_t c = (room - (uint64_t)l) / spc;
        if ((c + 2 + per_sector - 1) / per_sector != (uint64_t)l) continue;
        *fat_len = (uint32_t)l;
        *clu_count = (uint32_t)c;
        return 0;
    }
    return -1;
}

/* One run of `n` clusters starting at `start`: each FAT entry points at the
 * next, the last carries the end-of-chain marker.  Returns the first free
 * cluster after the run. */
static uint32_t exfat_fat_chain(uint8_t *fat, uint32_t start, uint32_t n) {
    for (uint32_t i = 0; i < n; i++)
        le32(fat + (size_t)(start + i) * EXFAT_FAT_ENTRY,
             (i + 1 == n) ? EXFAT_EOF : start + i + 1);
    return start + n;
}

int cfs_mkfs_exfat(CFS *c, uint64_t disk_sz) {
    return cfs_mkfs_exfat_at(c, 0, disk_sz);
}

int cfs_mkfs_exfat_at(CFS *c, uint64_t base_off, uint64_t size) {
    if (!c || base_off % EXFAT_SECTOR) return -1;
    /* Capacity first: cfs_block_write refuses anything past the declared
     * size, so the formatter must declare it before it writes. */
    if (cfs_block_resize(c, base_off + size) != 0) return -1;

    uint64_t total_sects = size / EXFAT_SECTOR;

    /* Cluster size by volume size, the way mkfs.fat picks sectors per
     * cluster: exFAT's own recommendation (4KB up to 256MB, 32KB up to
     * 32GB, 128KB above).  Shrink or grow from there until ClusterCount is
     * inside exFAT's window — a smaller cluster means more of them — and
     * refuse rather than write a volume whose cluster count is illegal. */
    uint32_t spc = total_sects < 256ull * 1024 * 1024 / EXFAT_SECTOR ? 8 :
                   total_sects < 32ull * 1024 * 1024 * 1024 / EXFAT_SECTOR ? 64 : 256;
    uint32_t fat_len = 0, clu_count = 0;
    for (;;) {
        if (exfat_layout(total_sects, spc, &fat_len, &clu_count) == 0) {
            if (clu_count < EXFAT_MIN_CLUSTERS) {
                if (spc > 1) { spc >>= 1; continue; }
                return -1;
            }
            if (clu_count > EXFAT_MAX_CLUSTERS) {
                if (spc < EXFAT_MAX_SPC) { spc <<= 1; continue; }
                return -1;
            }
            break;
        }
        /* No solution at all means the volume is too small for even a
         * 512-byte cluster, and a larger cluster only makes it worse. */
        if (spc > 1) { spc >>= 1; continue; }
        return -1;
    }

    const uint32_t csz = spc * EXFAT_SECTOR;             /* bytes per cluster */
    const uint64_t clu_off = EXFAT_FAT_OFF + fat_len;    /* heap start, sectors */
    const uint64_t bitmap_bytes = ((uint64_t)clu_count + 7) / 8;
    /* The bitmap covers ClusterCount bits exactly, so the entry's DataLength
     * is that byte count even though the stream is rounded up to clusters. */
    const uint32_t bitmap_clus = (uint32_t)((bitmap_bytes + csz - 1) / csz);
    const uint32_t upcase_clus = (uint32_t)((EXFAT_UPCASE_BYTES + csz - 1) / csz);
    const uint32_t bitmap_start = EXFAT_FIRST_CLU;
    const uint32_t upcase_start = bitmap_start + bitmap_clus;
    const uint32_t root_start   = upcase_start + upcase_clus;
    const uint32_t used_clus    = bitmap_clus + upcase_clus + 1;
    if (used_clus > clu_count) return -1;

    uint8_t shift = 0;
    for (uint32_t t = spc; t > 1; t >>= 1) shift++;

    uint32_t serial = (uint32_t)time(NULL) ^ ((uint32_t)getpid() << 16);

    /* ── boot regions ─────────────────────────────────────────────
     * Main region sectors 0..11 and the backup at 12..23.  The backup boot
     * sector is a byte-identical copy of the main one, so the checksum
     * computed over the backup's sectors is the same value. */
    const size_t br_sz = EXFAT_BOOT_SECT * EXFAT_SECTOR;
    uint8_t *br = calloc(1, br_sz);
    if (!br) return -1;
    uint8_t *bs = br;                                    /* sector 0 */
    bs[0] = 0xEB; bs[1] = 0x76; bs[2] = 0x90;            /* jmp short +0x76 */
    memcpy(bs + 3, "EXFAT   ", 8);
    le64(bs + 64, base_off / EXFAT_SECTOR);              /* PartitionOffset */
    le64(bs + 72, total_sects);                          /* VolumeLength */
    le32(bs + 80, EXFAT_FAT_OFF);                        /* FatOffset */
    le32(bs + 84, fat_len);                              /* FatLength */
    le32(bs + 88, (uint32_t)clu_off);                    /* ClusterHeapOffset */
    le32(bs + 92, clu_count);                            /* ClusterCount */
    le32(bs + 96, root_start);                           /* FirstClusterOfRootDirectory */
    le32(bs + 100, serial);                              /* VolumeSerialNumber */
    le16(bs + 104, 0x0100);                              /* FileSystemRevision 1.00 */
    le16(bs + 106, 0);                                   /* VolumeFlags: clean */
    bs[108] = 9;                                         /* BytesPerSectorShift */
    bs[109] = shift;                                     /* SectorsPerClusterShift */
    bs[110] = 1;                                         /* NumberOfFats */
    bs[111] = 0x80;                                      /* DriveSelect */
    bs[112] = (uint8_t)((uint64_t)used_clus * 100 / clu_count);  /* PercentInUse */
    le16(bs + 510, 0xAA55);                              /* BootSignature */

    /* Extended boot sectors 1..8: zero except the 0xAA550000 signature that
     * sits in their last four bytes.  OEM parameters (9) and reserved (10)
     * stay zero, which is how they are left unused. */
    for (int i = 1; i <= 8; i++) le32(br + i * EXFAT_SECTOR + 508, 0xAA550000u);

    /* Checksum sector 11: the region checksum repeated to fill the sector. */
    uint32_t bsum = exfat_checksum(br, 11 * EXFAT_SECTOR, 1);
    for (int i = 0; i < EXFAT_SECTOR / 4; i++)
        le32(br + 11 * EXFAT_SECTOR + i * 4, bsum);
    memcpy(br + 12 * EXFAT_SECTOR, br, 11 * EXFAT_SECTOR);
    memcpy(br + 23 * EXFAT_SECTOR, br + 11 * EXFAT_SECTOR, EXFAT_SECTOR);

    /* ── FAT ──────────────────────────────────────────────────────
     * Only the entries up to the root directory's last cluster are ever
     * non-zero, so the tail of the FAT is left unwritten: a fresh container
     * reads holes back as zeros, which is exactly "free cluster". */
    uint64_t fat_used = ((uint64_t)root_start + 1) * EXFAT_FAT_ENTRY;
    uint32_t fat_sects_used = (uint32_t)((fat_used + EXFAT_SECTOR - 1) / EXFAT_SECTOR);
    if (fat_sects_used > fat_len) fat_sects_used = fat_len;
    uint8_t *fat = calloc(1, (size_t)fat_sects_used * EXFAT_SECTOR);
    if (!fat) { free(br); return -1; }
    le32(fat + 0, EXFAT_FAT0);
    le32(fat + EXFAT_FAT_ENTRY, EXFAT_EOF);
    uint32_t next = exfat_fat_chain(fat, bitmap_start, bitmap_clus);
    next = exfat_fat_chain(fat, next, upcase_clus);
    exfat_fat_chain(fat, next, 1);                       /* root directory */

    /* ── allocation bitmap ────────────────────────────────────────
     * A set bit means allocated, so it covers the bitmap, the up-case table
     * and the root directory — including the bitmap's own clusters.  Only
     * the set prefix is written; the rest of the bitmap is a hole, i.e.
     * zero, i.e. free. */
    uint32_t bm_sects = (uint32_t)((used_clus / 8 + 1 + EXFAT_SECTOR - 1) / EXFAT_SECTOR);
    uint8_t *bm = calloc(1, (size_t)bm_sects * EXFAT_SECTOR);
    if (!bm) { free(br); free(fat); return -1; }
    memset(bm, 0xFF, used_clus / 8);
    if (used_clus % 8) bm[used_clus / 8] = (uint8_t)((1u << (used_clus % 8)) - 1);

    /* ── root directory ───────────────────────────────────────────
     * Three real entries then the zero byte that ends the directory.  The
     * label is 11 UTF-16 code units, space padded and without a terminator,
     * the shape cfs_mkfs_fat32 gives its FAT32 label. */
    static const uint16_t label[11] = {
        'C', 'F', 'S', '-', 'D', 'I', 'S', 'K', ' ', ' ', ' '
    };
    uint8_t root[3 * 32];
    memset(root, 0, sizeof(root));
    root[0] = 0x83;                                      /* VolumeLabel */
    root[1] = 11;
    for (int i = 0; i < 11; i++) le16(root + 2 + i * 2, label[i]);
    root[32] = 0x81;                                     /* AllocationBitmap */
    le32(root + 32 + 20, bitmap_start);                  /* FirstCluster */
    le64(root + 32 + 24, bitmap_bytes);                  /* DataLength */
    root[64] = 0x82;                                     /* UpCaseTable */
    le32(root + 64 + 4, exfat_checksum(exfat_upcase, EXFAT_UPCASE_BYTES, 0));
    le32(root + 64 + 20, upcase_start);                  /* FirstCluster */
    le64(root + 64 + 24, EXFAT_UPCASE_BYTES);            /* DataLength */

    const uint64_t heap = base_off + clu_off * EXFAT_SECTOR;
    int rc = 0;
    if (cfs_block_write(c, br, br_sz, (off_t)base_off) != 0 ||
        cfs_block_write(c, fat, (size_t)fat_sects_used * EXFAT_SECTOR,
                        (off_t)(base_off + EXFAT_FAT_OFF * EXFAT_SECTOR)) != 0 ||
        cfs_block_write(c, bm, (size_t)bm_sects * EXFAT_SECTOR,
                        (off_t)(heap + (uint64_t)(bitmap_start - EXFAT_FIRST_CLU) * csz)) != 0 ||
        cfs_block_write(c, exfat_upcase, EXFAT_UPCASE_BYTES,
                        (off_t)(heap + (uint64_t)(upcase_start - EXFAT_FIRST_CLU) * csz)) != 0 ||
        cfs_block_write(c, root, sizeof(root),
                        (off_t)(heap + (uint64_t)(root_start - EXFAT_FIRST_CLU) * csz)) != 0)
        rc = -1;
    free(br);
    free(fat);
    free(bm);
    if (rc != 0) return -1;

    fprintf(stderr, "cfs: exfat: %llu clusters, %u/sector, fat=%u sectors, "
                    "heap=%llu, root=%u\n",
            (unsigned long long)clu_count, spc, fat_len,
            (unsigned long long)clu_off, root_start);
    return 0;
}

